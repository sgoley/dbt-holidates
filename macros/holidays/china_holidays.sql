{% macro _china_holiday_rows(start_year, end_year) %}
    {% set rows = [] %}
    {% set lunar_dates = dbt_holidates._china_lunar_dates() %}
    {% for year in range(start_year, end_year + 1) %}
        {% set calendar = "china" %}
        {% set display = "China Holidays" %}
        {% set country = "CN" %}
        {% set holiday_type = "public_holiday" %}

        {% set actual = dbt_holidates._date(year, 1, 1) %}
        {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, actual, actual, "New Year's Day", holiday_type, "January 1")) %}
        {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, dbt_holidates._qib_qingming(year), dbt_holidates._qib_qingming(year), "Qingming Festival", holiday_type, "Solar term Qingming, generally April 4 or April 5")) %}
        {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, dbt_holidates._date(year, 5, 1), dbt_holidates._date(year, 5, 1), "Labour Day", holiday_type, "May 1")) %}
        {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, dbt_holidates._date(year, 10, 1), dbt_holidates._date(year, 10, 1), "National Day", holiday_type, "October 1")) %}

        {% if lunar_dates.get(year) %}
            {% set lunar = lunar_dates.get(year) %}
            {% set spring = modules.datetime.date.fromisoformat(lunar["spring_festival"]) %}
            {% set dragon = modules.datetime.date.fromisoformat(lunar["dragon_boat"]) %}
            {% set mid_autumn = modules.datetime.date.fromisoformat(lunar["mid_autumn"]) %}
            {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, spring, spring, "Spring Festival", holiday_type, "First day of the first lunar month; curated through 2050")) %}
            {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, dragon, dragon, "Dragon Boat Festival", holiday_type, "Fifth day of the fifth lunar month; curated through 2050")) %}
            {% do rows.append(dbt_holidates._holiday_row(calendar, display, country, none, mid_autumn, mid_autumn, "Mid-Autumn Festival", holiday_type, "Fifteenth day of the eighth lunar month; curated through 2050")) %}
        {% endif %}
    {% endfor %}
    {{ return(rows) }}
{% endmacro %}
